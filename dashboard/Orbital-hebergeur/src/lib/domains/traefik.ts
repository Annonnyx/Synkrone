import fs from "node:fs/promises";
import path from "node:path";
import { eq } from "drizzle-orm";
import { db } from "@/db";
import { containers, domains, services, webProjects } from "@/db/schema";
import { PLACEHOLDER_PUBLIC_DOMAIN } from "./public";

function isPlaceholderHost(hostname: string): boolean {
  return (
    hostname === PLACEHOLDER_PUBLIC_DOMAIN || hostname.endsWith(`.${PLACEHOLDER_PUBLIC_DOMAIN}`)
  );
}

function dynamicDir(): string {
  return (
    process.env.ORBITAL_TRAEFIK_DYNAMIC_DIR?.trim() ||
    path.join(process.cwd(), "docker/proxy/dynamic")
  );
}

function yamlEscape(value: string): string {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

export async function syncTraefikConfig(serviceId: string): Promise<boolean> {
  const [svc] = await db.select().from(services).where(eq(services.id, serviceId)).limit(1);
  if (!svc || svc.type !== "web") return false;
  const rows = await db.select().from(domains).where(eq(domains.serviceId, serviceId));
  const file = path.join(dynamicDir(), `${serviceId}.yml`);

  if (!rows.length) {
    await fs.unlink(file).catch(() => undefined);
    return true;
  }

  const [web] = await db.select().from(webProjects).where(eq(webProjects.serviceId, serviceId)).limit(1);
  const [container] = await db
    .select()
    .from(containers)
    .where(eq(containers.serviceId, serviceId))
    .limit(1);
  const containerName = container?.containerName ?? `web-${svc.slug}-${svc.id.slice(0, 8)}`;
  const port = web?.port ?? 3000;
  const hosts = rows.map((d) => `Host(\`${d.hostname}\`)`).join(" || ");
  const https = rows.some((d) => d.https && !isPlaceholderHost(d.hostname));
  const resolver = rows.find((d) => d.https && !isPlaceholderHost(d.hostname))?.certResolver || "letsencrypt";
  const tls = https
    ? `\n      tls:\n        certResolver: ${yamlEscape(resolver)}`
    : "";

  const yaml = `# generated by Orbital — do not edit by hand
http:
  routers:
    orbital-${yamlEscape(svc.slug)}:
      rule: "${yamlEscape(hosts)}"
      service: orbital-${yamlEscape(svc.slug)}
      entryPoints:
        - web${https ? "\n        - websecure" : ""}${tls}
  services:
    orbital-${yamlEscape(svc.slug)}:
      loadBalancer:
        servers:
          - url: "http://${yamlEscape(containerName)}:${port}"
`;

  try {
    await fs.mkdir(dynamicDir(), { recursive: true });
    await fs.writeFile(file, yaml, "utf8");
    return true;
  } catch {
    return false;
  }
}
