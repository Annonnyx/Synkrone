import { eq } from "drizzle-orm";
import { db } from "@/db";
import { minecraftServers, containers } from "@/db/schema";
import { HttpError } from "@/lib/auth";
import { ContainerManager } from "@/lib/docker/adapter";
import { defaultProperties } from "@/lib/minecraft/properties";
import type { ServiceType } from "@/lib/paths";
import { appendConsole, BaseRuntimeProvider, setServiceState } from "./base";
import { minecraftTemplate, type MinecraftSoftware } from "./templates";
import type { RuntimeTemplate, ServiceRecord } from "./types";

export const DEFAULT_PROPERTIES: Record<string, string> = defaultProperties();

export function serializeProperties(props: Record<string, string>): string {
  return [
    "# Managed by Orbital - edits from the panel are written here",
    `# ${new Date().toISOString()}`,
    ...Object.entries(props)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([k, v]) => `${k}=${v}`),
  ].join("\n");
}

export function parseProperties(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of text.split(/\r?\n/)) {
    if (!line.trim() || line.trim().startsWith("#")) continue;
    const idx = line.indexOf("=");
    if (idx === -1) continue;
    out[line.slice(0, idx).trim()] = line.slice(idx + 1).trim();
  }
  return out;
}

export class MinecraftRuntimeProvider extends BaseRuntimeProvider {
  readonly type: ServiceType = "minecraft";

  async scaffold(service: ServiceRecord): Promise<void> {
    const fsm = this.fs(service.id);
    const mc = await this.record(service.id);
    const props = { ...DEFAULT_PROPERTIES, ...(mc?.properties ?? {}) };
    props["server-port"] = String(mc?.javaPort ?? 25565);
    await fsm.write("server.properties", serializeProperties(props));
    await fsm.write("eula.txt", `# Minecraft EULA acceptance recorded in the panel\neula=${mc?.eulaAccepted ? "true" : "false"}\n`);
    await fsm.mkdir("plugins");
    await fsm.mkdir("mods");
    await fsm.mkdir("config");
    await fsm.mkdir("logs");
    await fsm.mkdir("world");
    if (mc?.bedrockEnabled) {
      await fsm.mkdir("plugins/Geyser-Spigot");
      await fsm.write(
        "plugins/Geyser-Spigot/config.yml",
        `# Geyser configuration generated by Orbital\nbedrock:\n  port: ${mc.bedrockPort}\n  clone-remote-port: false\nremote:\n  address: 127.0.0.1\n  port: ${mc.javaPort}\n  auth-type: floodgate\n`,
      );
    }
  }

  private async record(serviceId: string) {
    return (
      await db
        .select()
        .from(minecraftServers)
        .where(eq(minecraftServers.serviceId, serviceId))
        .limit(1)
    )[0];
  }

  protected async template(service: ServiceRecord): Promise<RuntimeTemplate> {
    const mc = await this.record(service.id);
    return minecraftTemplate(
      (mc?.software ?? "paper") as MinecraftSoftware,
      mc?.version ?? "1.21.1",
      service.memoryLimitMb,
    );
  }

  protected async extraEnv(service: ServiceRecord): Promise<Record<string, string>> {
    const mc = await this.record(service.id);
    const env: Record<string, string> = {
      EULA: mc?.eulaAccepted ? "TRUE" : "FALSE",
      SERVER_PORT: String(mc?.javaPort ?? 25565),
      MOTD: mc?.properties?.motd ?? DEFAULT_PROPERTIES.motd,
      DIFFICULTY: mc?.properties?.difficulty ?? "normal",
      MAX_PLAYERS: mc?.properties?.["max-players"] ?? "20",
      OVERRIDE_SERVER_PROPERTIES: "false",
    };
    if (mc?.bedrockEnabled) {
      env.PLUGINS_SYNC_UPDATE = "true";
      env.SPIGET_RESOURCES = "34261,32826"; // Geyser-Spigot, Floodgate
      env.BEDROCK_PORT = String(mc.bedrockPort);
    }
    return env;
  }

  protected async ports(service: ServiceRecord) {
    const mc = await this.record(service.id);
    const java = mc?.javaPort ?? 25565;
    const ports = [{ containerPort: 25565, hostPort: java, protocol: "tcp" as const }];
    if (mc?.bedrockEnabled) {
      ports.push({
        containerPort: 19132,
        hostPort: mc.bedrockPort,
        protocol: "udp" as unknown as "tcp",
      });
    }
    return ports;
  }

  /**
   * itzg's mc-server-runner owns container stdin. A pooled attach that later
   * drops (HMR, daemon recycle) EOF's that pipe and every later attach "succeeds"
   * without the JVM seeing a byte. Writing to the Java process fd/0 reaches the
   * server console even after the wrapper pipe is dead.
   */
  private async writeMinecraftConsole(containerId: string, command: string): Promise<void> {
    const quoted = `'${command.replace(/'/g, `'\\''`)}'`;
    const result = await ContainerManager.execCommand(containerId, [
      "sh",
      "-lc",
      `pid=$(pgrep -n java 2>/dev/null || true); if [ -n "$pid" ] && [ -w "/proc/$pid/fd/0" ]; then printf '%s\\n' ${quoted} > "/proc/$pid/fd/0"; else exit 42; fi`,
    ]);
    if (result.exitCode === 0) return;
    await ContainerManager.writeStdin(containerId, command);
  }

  /**
   * Send `stop` to the JVM first so the world saves, then give Docker a long
   * enough timeout. itzg's default announce delay used to eat the 20s stop
   * window and the engine SIGKILL'd the process (exit 137, shown as a crash).
   */
  async stop(serviceId: string) {
    const row = await this.requireContainer(serviceId);
    await setServiceState(serviceId, "STOPPING");
    await appendConsole(serviceId, "Stopping container...");
    if (row.dockerContainerId) {
      try {
        await this.writeMinecraftConsole(row.dockerContainerId, "stop");
        await appendConsole(serviceId, "Sent stop to the Minecraft process");
      } catch {
        /* docker stop still runs */
      }
      await ContainerManager.stopContainer(row.dockerContainerId, 60);
    }
    await db.update(containers).set({ status: "STOPPED" }).where(eq(containers.id, row.id));
    await setServiceState(serviceId, "STOPPED");
    await appendConsole(serviceId, "Container stopped");
  }

  /** Minecraft commands go to the server process stdin (§26). */
  async sendCommand(serviceId: string, command: string): Promise<string> {
    const row = await this.requireContainer(serviceId);
    // Attaching to a container that is not running blocks instead of failing,
    // so the state is checked before the write rather than after a timeout.
    const status = await this.status(serviceId);
    if (status.state !== "RUNNING") {
      throw new HttpError(409, "The server is not running - start it before sending commands");
    }
    await appendConsole(serviceId, `> ${command}`, "command");
    try {
      await this.writeMinecraftConsole(row.dockerContainerId!, command);
    } catch (err) {
      await appendConsole(serviceId, (err as Error).message, "stderr");
      throw err;
    }
    return "sent";
  }
}
