const PANELBOT_CONFIG_PATHS = [
  "cogs/DEV/panelbot/bot_config.json",
  "cogs/owner/commands/panelbot/bot_config.json",
];

function skipCopy(name: string) {
  return (
    name === "__pycache__" ||
    name === ".venv" ||
    name === "venv" ||
    name === ".git" ||
    name === ".env" ||
    name.endsWith(".pyc")
  );
}

async function ensurePythonPackages(root: string, relFile: string) {
  const parts = path.dirname(relFile).split(/[/\\]/).filter(Boolean);
  let current = root;
  for (const part of parts) {
    current = path.join(current, part);
    await mkdir(current, { recursive: true });
    await writeFile(path.join(current, "__init__.py"), "", { flag: "a" });
  }
}

export class DiscordRuntimeProvider extends BaseRuntimeProvider {
  readonly type: ServiceType = "discord";

  async scaffold(service: ServiceRecord): Promise<void> {
    const fsm = this.fs(service.id);
    const bot = (
      await db.select().from(discordBots).where(eq(discordBots.serviceId, service.id)).limit(1)
    )[0];
    const flavor = bot?.flavor || flavorFromModules(bot?.modules ?? []);
    const root = synkroneRepoRoot();

    if (flavor !== "custom") {
      const official = officialBot(flavor);
      if (!official) throw new Error(`Unknown official bot: ${flavor}`);
      const source = path.join(root, official.dir);
      await cp(source, fsm.root, {
        recursive: true,
        filter: (src) => !skipCopy(path.basename(src)),
      });
    } else {
      const templateRoot = path.join(root, "templates/discord");
      await mkdir(path.join(fsm.root, "cogs"), { recursive: true });
      await mkdir(path.join(fsm.root, "config"), { recursive: true });
      await writeFile(path.join(fsm.root, "cogs", "__init__.py"), "", { flag: "a" });
      await cp(path.join(templateRoot, "cogs/config_manager"), path.join(fsm.root, "cogs/config_manager"), {
        recursive: true,
        filter: (src) => !skipCopy(path.basename(src)),
      }).catch(() => undefined);
      const enabled: string[] = [];
      const commands = (bot?.commands ?? []).filter((c) => c.enabled);
      for (const cmd of commands) {
        const mapped = cogForCommand(cmd) ?? COMMAND_COGS[cmd.name] ?? COMMAND_COGS[cmd.module];
        const rel = mapped?.file;
        if (!rel) continue;
        const from = path.join(templateRoot, rel);
        await ensurePythonPackages(fsm.root, rel);
        await cp(path.dirname(from), path.join(fsm.root, path.dirname(rel)), {
          recursive: true,
          filter: (src) => !skipCopy(path.basename(src)),
        }).catch(() => undefined);
        enabled.push(rel.replace(/\.py$/i, "").replaceAll("\\", "/").replaceAll("/", "."));
      }
      if (!enabled.includes("cogs.config_manager.stats_store")) {
        enabled.push("cogs.config_manager.stats_store");
      }
      await fsm.write("main.py", CUSTOM_MAIN_PY);
      await fsm.write("config/enabled_cogs.json", JSON.stringify(enabled, null, 2));
      try {
        await fsm.write("requirements.txt", await readFile(path.join(templateRoot, "requirements.txt"), "utf8"));
      } catch {
        await fsm.write("requirements.txt", "discord.py>=2.3.2\npython-dotenv>=1.0.0\naiohttp>=3.8.4\n");
      }
    }

    await this.writePlatformRuntime(service);
    await fsm.write(
      "README.md",
      `# ${service.name}\n\nBot Python Synkrone (${flavor}). Éditez les fichiers ici ou via SFTP, puis redémarrez.\n`,
    );
  }

  async syncPlatformRuntime(service: ServiceRecord) {
    await this.writePlatformRuntime(service);
  }

  private async writePlatformRuntime(service: ServiceRecord) {
    const fsm = this.fs(service.id);
    const bot = (
      await db.select().from(discordBots).where(eq(discordBots.serviceId, service.id)).limit(1)
    )[0];
    const flavor = bot?.flavor ?? "custom";
    const prefix = bot?.prefix ?? "!";
    const intents = resolveGatewayIntents(bot?.intents, bot?.modules ?? []);
    await fsm.write(".orbital/boot.sh", BOOT_SH);
    await fsm.write(
      "config/bot.json",
      JSON.stringify(
        {
          name: service.name,
          flavor,
          prefix,
          slashCommands: bot?.slashCommands ?? true,
          intents,
          intentsBitfield: intentsBitfield(intents),
          modules: bot?.modules ?? [],
        },
        null,
        2,
      ),
    );
    await this.syncPanelbotPrefix(fsm, prefix);
    await this.writeSlashHelper(fsm);
    if (flavor === "custom") {
      await this.refreshGeneratedMain(fsm);
    } else {
      await fsm.write("cogs/synkrone_runtime.py", SYNKRONE_RUNTIME_PY);
    }
  }

  private async writeSlashHelper(fsm: FilesystemManager) {
    try {
      const source = await readFile(
        path.join(synkroneRepoRoot(), "templates/discord/synkrone_slash.py"),
        "utf8",
      );
      await fsm.write("synkrone_slash.py", source);
    } catch {
      /* template missing in a partial checkout — generated main still has a fallback import */
    }
  }

  private async syncPanelbotPrefix(fsm: FilesystemManager, prefix: string) {
    for (const rel of PANELBOT_CONFIG_PATHS) {
      try {
        const raw = await fsm.read(rel);
        const json = JSON.parse(raw) as Record<string, unknown>;
        if (json.prefix === prefix) continue;
        json.prefix = prefix;
        await fsm.write(rel, `${JSON.stringify(json, null, 4)}\n`);
      } catch {
        /* bot has no panelbot config at this path */
      }
    }
  }

  private async refreshGeneratedMain(fsm: FilesystemManager) {
    try {
      const current = await fsm.read("main.py");
      if (!current.startsWith("# Generated by Synkrone")) return;
    } catch {
      return;
    }
    await fsm.write("main.py", CUSTOM_MAIN_PY);
  }

  protected async template(): Promise<RuntimeTemplate> {
    return DISCORD_TEMPLATE;
  }

  protected async extraEnv(service: ServiceRecord): Promise<Record<string, string>> {
    const bot = (
      await db.select().from(discordBots).where(eq(discordBots.serviceId, service.id)).limit(1)
    )[0];
    const token = await this.storedToken(service.id);
    const configSecret =
      process.env.SESSION_SECRET || process.env.BOT_CONFIG_SECRET || process.env.PLATFORM_SECRET_KEY || "";
    const siteOrigin = String(process.env.PUBLIC_ORIGIN || process.env.ORBITAL_PUBLIC_ORIGIN || "")
      .trim()
      .replace(/\/hebergement\/?$/, "")
      .replace(/\/$/, "");
    return {
      PYTHONUNBUFFERED: "1",
      PREFIX: bot?.prefix ?? "!",
      BOT_PREFIX: bot?.prefix ?? "!",
      ENABLE_SLASH_COMMANDS: String(bot?.slashCommands ?? true),
      ...(configSecret
        ? { BOT_CONFIG_SECRET: configSecret, SESSION_SECRET: configSecret }
        : {}),
      ...(siteOrigin ? { PUBLIC_SITE_ORIGIN: siteOrigin } : {}),
      ...(token ? { BOT_TOKEN: token, DISCORD_TOKEN: token } : {}),
    };
  }

  async create(service: ServiceRecord) {
    const token = await this.storedToken(service.id);
    await appendConsole(
      service.id,
      token
        ? "Discord token attached to the container"
        : "No Discord token yet — add it in the Token tab before starting",
    );
    return super.create({
      ...service,
      restartPolicy: service.restartPolicy === "always" ? "always" : "no",
      maxRestarts: 0,
    });
  }

  async start(serviceId: string) {
    await this.requireToken(serviceId);
    const record = await loadServiceRecord(serviceId);
    if (!record) throw new Error("Service not found");
    await this.writePlatformRuntime(record);
    await this.ensureTokenInjected(serviceId);
    await super.start(serviceId);
  }

  async restart(serviceId: string) {
    const token = await this.storedToken(serviceId);
    if (!token) {
      const row = await currentContainer(serviceId);
      if (row?.dockerContainerId && (await this.containerHasToken(row.dockerContainerId)) === true) {
        await super.restart(serviceId);
        return;
      }
      await this.requireToken(serviceId);
    }
    const record = await loadServiceRecord(serviceId);
    if (!record) throw new Error("Service not found");
    await this.writePlatformRuntime(record);
    await this.ensureTokenInjected(serviceId);
    await super.restart(serviceId);
  }

  private async storedToken(serviceId: string): Promise<string | null> {
    const bot = (
      await db.select().from(discordBots).where(eq(discordBots.serviceId, serviceId)).limit(1)
    )[0];
    const fromEnc = decryptSecret(bot?.tokenEnc);
    if (fromEnc) {
      if (bot?.id && bot.tokenEnc && !opensWithPreferredKey(bot.tokenEnc)) {
        await db
          .update(discordBots)
          .set({ tokenEnc: encryptSecret(fromEnc) })
          .where(eq(discordBots.id, bot.id));
      }
      return fromEnc;
    }
    const env = await serviceEnvironment(serviceId);
    const fromEnv = (env.DISCORD_TOKEN || env.BOT_TOKEN || "").trim();
    return fromEnv || null;
  }

  private async requireToken(serviceId: string): Promise<string> {
    const bot = (
      await db.select().from(discordBots).where(eq(discordBots.serviceId, serviceId)).limit(1)
    )[0];
    const token = await this.storedToken(serviceId);
    if (token) return token;
    if (bot?.tokenEnc) throw new Error("BOT_TOKEN is stored but cannot be decrypted");
    throw new Error("BOT_TOKEN is not set");
  }

  private async containerHasToken(containerId: string): Promise<boolean | null> {
    try {
      const inspect = await ContainerManager.inspect(containerId);
      const env = inspect.Config?.Env;
      if (!Array.isArray(env)) return null;
      return env.some((entry) => /^(BOT_TOKEN|DISCORD_TOKEN)=.+$/.test(entry));
    } catch {
      return null;
    }
  }

  private async ensureTokenInjected(serviceId: string) {
    const row = await currentContainer(serviceId);
    if (row?.dockerContainerId) {
      const hasToken = await this.containerHasToken(row.dockerContainerId);
      if (hasToken === true) return;
      await appendConsole(serviceId, "Applying the saved Discord token to a new container...");
      await this.remove(serviceId);
    }
    const record = await loadServiceRecord(serviceId);
    if (!record) throw new Error("Service not found");
    await this.create(record);
  }
}

void DISALLOWED_INTENTS_FATAL;
